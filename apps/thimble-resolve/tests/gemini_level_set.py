#!/usr/bin/env python3
"""
Level-set POC: same facilitator-intake-system-prompt.md, same scenarios,
one arm run through Claude (today's real engine) and one arm run through
Gemini instead -- to see how much changes if Thimble's replies were
generated by Gemini using the prompting we already built, rather than by
paying for Claude on every turn.

Deliberately narrower than benchmark_audit.py: this does NOT compare against
raw ChatGPT/raw Claude/raw Gemini (no system prompt) -- that script already
answers "why not just use a generic chatbot." This answers a different
question: "if we keep our prompt but swap the model underneath it, how much
does the facilitator's actual behavior change." Reuses benchmark_audit.py's
scenario set, system-prompt loader, signal-stripping, and Claude judge so
the rubric and scoring are identical and comparable.

Needs ANTHROPIC_API_KEY (engine + judge) and GEMINI_API_KEY in thimble/.env.

Usage:
    thimble/.venv/bin/python thimble/tests/gemini_level_set.py [--repeats 1] [--max-turns 4] [--scenarios N]
"""
import argparse
import os
import random
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

from anthropic import Anthropic
from dotenv import load_dotenv

sys.path.insert(0, str(Path(__file__).parent))
from benchmark_audit import (  # noqa: E402
    CLAUDE_MODEL,
    SCENARIOS,
    format_transcript,
    get_anthropic_client,
    has_real_question,
    judge,
    strip_mend_signal,
)

# benchmark_audit.py's own SYSTEM_PROMPT_FILE still points at the pre-rename
# filename (apps/facilitator-intake-system-prompt.md) -- that rename is
# in-flight in another session elsewhere in this repo, so this script reads
# the current filename directly rather than patching that shared file here.
_SYSTEM_PROMPT_FILE = Path(__file__).parent.parent.parent / "facilitator-thimble-resolve-intake-system-prompt.md"


def load_mend_system_prompt() -> str:
    import re
    text = _SYSTEM_PROMPT_FILE.read_text()
    match = re.search(r"```\n(.*?)\n```", text, re.S)
    if not match:
        raise RuntimeError(f"couldn't find fenced system prompt in {_SYSTEM_PROMPT_FILE}")
    return match.group(1)

ROOT = Path(__file__).parent.parent
load_dotenv(ROOT / ".env")

GEMINI_MODEL = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash")
# The free GEMINI_API_KEY in .env sits on an unbilled AI Studio project
# (gen-lang-client-0781004317, billingEnabled=false) -- confirmed via
# `gcloud billing projects describe`, it was never touching the $2000 GCP
# credit, just a free daily quota. That credit lives on a separate,
# billing-enabled project with Vertex AI already turned on and working
# `gcloud auth application-default` creds, so this POC calls Gemini through
# Vertex AI on that project instead of the AI Studio API key.
VERTEX_PROJECT = os.environ.get("VERTEX_PROJECT", "project-cda29313-2129-4061-bec")
VERTEX_LOCATION = os.environ.get("VERTEX_LOCATION", "global")


def call_mend_claude(client: Anthropic, system_prompt: str, messages: list[dict]) -> tuple[str, str | None]:
    resp = client.messages.create(
        model=CLAUDE_MODEL, max_tokens=8192,
        system=[{"type": "text", "text": system_prompt, "cache_control": {"type": "ephemeral"}}],
        messages=messages,
    )
    raw = "".join(b.text for b in resp.content if b.type == "text")
    if not raw:
        raise RuntimeError(f"mend_claude call returned no text, stop_reason={resp.stop_reason}")
    return strip_mend_signal(raw)


def call_mend_gemini(system_prompt: str, messages: list[dict]) -> tuple[str, str | None]:
    """Same system prompt as the real facilitator, same conversation turns,
    just handed to Gemini's generate_content instead of Anthropic's
    messages.create -- the actual engine swap this POC exists to test.
    Goes through Vertex AI (not the AI Studio GEMINI_API_KEY) so usage
    actually draws on the $2000 GCP credit -- see VERTEX_PROJECT comment
    above for why."""
    from google import genai
    from google.genai import types as genai_types

    client = genai.Client(vertexai=True, project=VERTEX_PROJECT, location=VERTEX_LOCATION)
    contents = [
        genai_types.Content(
            role="model" if m["role"] == "assistant" else "user",
            parts=[genai_types.Part(text=m["content"])],
        )
        for m in messages
    ]
    resp = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=contents,
        config=genai_types.GenerateContentConfig(system_instruction=system_prompt, max_output_tokens=8192),
    )
    raw = resp.text or ""
    if not raw:
        raise RuntimeError(f"mend_gemini call returned no text, candidates={resp.candidates!r}")
    return strip_mend_signal(raw)


def run_system_adaptive(system_id: str, opening: str, followups: list[str], max_turns: int,
                         anthropic_client: Anthropic, mend_system_prompt: str
                         ) -> tuple[list[dict], list[str | None]]:
    messages = [{"role": "user", "content": opening}]
    signals: list[str | None] = []
    followup_idx = 0

    while True:
        if system_id == "mend_claude":
            reply, signal = call_mend_claude(anthropic_client, mend_system_prompt, messages)
        elif system_id == "mend_gemini":
            reply, signal = call_mend_gemini(mend_system_prompt, messages)
        else:
            raise ValueError(system_id)

        messages.append({"role": "assistant", "content": reply})
        signals.append(signal)

        turns_so_far = sum(1 for m in messages if m["role"] == "assistant")
        if turns_so_far >= max_turns or followup_idx >= len(followups) or not has_real_question(reply):
            break
        messages.append({"role": "user", "content": followups[followup_idx]})
        followup_idx += 1

    return messages, signals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    ap.add_argument("--repeats", type=int, default=1, help="independent passes per scenario")
    ap.add_argument("--max-turns", type=int, default=4)
    ap.add_argument("--scenarios", type=int, default=None, help="limit to first N scenarios (cheap dry run)")
    ap.add_argument("--scenario-ids", default=None, help="comma-separated scenario_id values to run instead of all/first-N")
    args = ap.parse_args()

    anthropic_client = get_anthropic_client()
    if anthropic_client is None:
        sys.exit("ANTHROPIC_API_KEY not set -- needed for the Claude engine AND the judge.")

    mend_system_prompt = load_mend_system_prompt()
    if args.scenario_ids:
        wanted = set(args.scenario_ids.split(","))
        scenarios = [s for s in SCENARIOS if s[0] in wanted]
        missing = wanted - {s[0] for s in scenarios}
        if missing:
            sys.exit(f"unknown scenario id(s): {missing}")
    else:
        scenarios = SCENARIOS[: args.scenarios] if args.scenarios else SCENARIOS

    results = []
    for scenario_id, opening, followups in scenarios:
        for rep in range(args.repeats):
            print(f"\n=== {scenario_id} (pass {rep + 1}/{args.repeats}) ===")
            system_ids_to_try = ["mend_claude", "mend_gemini"]
            passes: dict[str, tuple[list[dict], list[str | None]]] = {}
            for system_id in system_ids_to_try:
                try:
                    out = run_system_adaptive(system_id, opening, followups, args.max_turns,
                                               anthropic_client, mend_system_prompt)
                except Exception as e:
                    print(f"  {system_id}: ERROR {e}")
                    continue
                messages, signals = out
                turns_used = sum(1 for m in messages if m["role"] == "assistant")
                passes[system_id] = out
                print(f"  {system_id}: done ({turns_used} turn(s))")

            system_ids = list(passes.keys())
            random.shuffle(system_ids)
            labels = ["A", "B"][: len(system_ids)]
            label_map = dict(zip(labels, system_ids))

            pass_result = {"scenario_id": scenario_id, "rep": rep, "prompt": opening, "responses": {}}
            for label, system_id in label_map.items():
                messages, signals = passes[system_id]
                turns_used = sum(1 for m in messages if m["role"] == "assistant")
                transcript_text = format_transcript(messages, label)
                real_signals = [s for s in signals if s]
                signal_note = " | ".join(f"turn{i+1}={s}" for i, s in enumerate(signals) if s) if real_signals else None
                score = judge(anthropic_client, opening, label, transcript_text, signal_note, turns_used)
                pass_result["responses"][system_id] = {
                    "label_shown_to_judge": label,
                    "messages": messages,
                    "turns_used": turns_used,
                    "signal_note": signal_note,
                    "judge": score,
                }
                total = score.get("total")
                print(f"  judged {system_id} (shown as {label}, {turns_used}t): "
                      f"total={total if total is not None else score.get('rationale')}")
            results.append(pass_result)

    import json
    out_path = Path(args.out) if args.out else ROOT / "tests" / f"gemini_level_set_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}.json"
    out_path.write_text(json.dumps(results, indent=2))
    print(f"\nFull results saved to {out_path}")

    print("\n=== Aggregate totals by system ===")
    sums: dict[str, list[int]] = {}
    for pass_result in results:
        for system_id, data in pass_result["responses"].items():
            total = data["judge"].get("total")
            if isinstance(total, int):
                sums.setdefault(system_id, []).append(total)
    for system_id, totals in sums.items():
        avg = sum(totals) / len(totals)
        stdev = statistics.stdev(totals) if len(totals) > 1 else 0.0
        print(f"  {system_id:<12} avg={avg:.1f}/25  stdev={stdev:.1f}  n={len(totals)}  scores={totals}")


if __name__ == "__main__":
    main()
